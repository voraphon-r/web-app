const {test}=require('node:test'); const assert=require('node:assert/strict');
const {PGlite}=require('@electric-sql/pglite'); const fs=require('node:fs');
const setup=fs.readFileSync(__dirname+'/../supabase/setup.sql','utf8');
test('SQL setup, RLS, money constraints, immutable closed shifts and close totals',async()=>{
 const db=new PGlite();
 await db.exec(`create role anon; create role authenticated; create schema auth;
 create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
 create function auth.jwt() returns jsonb language sql stable as $$ select coalesce(nullif(current_setting('request.jwt.claims',true),''),'{}')::jsonb $$;
 grant usage on schema auth to authenticated; grant execute on all functions in schema auth to authenticated;
 create publication supabase_realtime;`);
 await db.exec(setup); await db.exec(setup);
 await db.exec(`insert into game_shop.members(email,display_name) values ('shop@example.com','ร้าน');
 set request.jwt.claim.sub='00000000-0000-4000-8000-000000000001';
 set request.jwt.claims='{"email":"shop@example.com"}'; set role authenticated;`);
 const reject=async(sql)=>assert.rejects(db.exec(sql));
 await reject(`insert into game_shop.members values ('evil@example.com','x',now())`);
 await db.exec(`insert into game_shop.shifts(staff_name) values ('ต้น')`);
 const id=(await db.query('select id from game_shop.shifts')).rows[0].id;
 await reject(`insert into game_shop.shifts(staff_name) values ('ซ้ำ')`);
 await reject(`insert into game_shop.shifts(id,staff_name) values (gen_random_uuid(),'x')`);
 const insert=(machine,game,drink,pay,received='null',eid='gen_random_uuid()')=>`insert into game_shop.shift_entries(id,shift_id,machine,game_amount,drink_amount,pay_method,cash_received) values (${eid},'${id}',${machine},${game},${drink},'${pay}',${received})`;
 for(const sql of [insert(21,30,0,'cash'),insert(1,"'NaN'",0,'cash'),insert(0,30,0,'cash'),insert(1,-1,0,'cash'),insert(1,0,0,'cash'),insert(1,50,0,'cash',20),insert(1,50,0,'transfer',100)]) await reject(sql);
 await db.exec(insert(3,100,14,'transfer'));
 await db.exec(insert(9,30,15,'cash'));
 await db.exec(insert(6,30,0,'cash'));
 await db.exec(insert(10,25,0,'cash'));
 const eid="'00000000-0000-4000-8000-000000000002'";
 await db.exec(insert(20,50,0,'cash',100,eid)); await reject(insert(10,50,0,'cash',100,eid));
 assert.equal((await db.query('select count(*)::int n from game_shop.shift_entries')).rows[0].n,5);
 await reject(`select game_shop.close_shift('${id}',5,149,114)`);
 await reject(`update game_shop.shift_entries set shift_id=gen_random_uuid() where id=${eid}`);
 await db.exec(`update game_shop.shift_entries set drink_amount=1 where id=${eid}; update game_shop.shift_entries set drink_amount=0 where id=${eid}`);
 await db.exec(`select game_shop.close_shift('${id}',5,150,114)`);
 await reject(insert(1,30,0,'cash'));
 await reject(`update game_shop.shift_entries set game_amount=60 where id=${eid}`);
 await reject(`delete from game_shop.shift_entries where id=${eid}`);
 await reject(`update game_shop.shifts set closed_at=null where id='${id}'`);
 await reject(`delete from game_shop.shifts where id='${id}'`);
 await db.exec(`set request.jwt.claims='{"email":"outsider@example.com"}'`);
 assert.equal((await db.query('select count(*)::int n from game_shop.shift_entries')).rows[0].n,0);
 await reject(`insert into game_shop.shifts(staff_name) values ('outsider')`);
 await db.exec('reset role; set role anon'); await reject('select * from game_shop.shift_entries');
 await db.exec('reset role'); await db.exec(setup);
 assert.equal((await db.query('select count(*)::int n from game_shop.shift_entries')).rows[0].n,5);
 await db.close();
});
